"""Build the in-site version of "You can just do things" from its standalone page.

Usage, from the repository root:
  python3 scripts/research/build_ycjdt_site.py path/to/public_page.html
  npx prettier --write src/app/research/you-can-just-do-things/article.css

The standalone page is produced outside this repository. This script splits it
into three generated files:
  src/app/research/you-can-just-do-things/article.css   styles scoped to .ycjdt
  src/app/research/you-can-just-do-things/content.ts    the article markup
  src/app/research/you-can-just-do-things/drawArticle.js  data and drawing script
"""
import json
import pathlib
import re
import sys

site = pathlib.Path(__file__).resolve().parents[2]
s = open(sys.argv[1]).read()
css = ''.join(re.findall(r'<style[^>]*>(.*?)</style>', s, re.S))
body = s[s.index('<body>') + 6:s.index('<script>')].strip()
js = s[s.index('<script>') + 8:s.rindex('</script>')]

S = '.ycjdt'


def split_top(text, sep=','):
    out, depth, cur = [], 0, ''
    for ch in text:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return [x.strip() for x in out if x.strip()]


def scope_sel(sel):
    if sel.startswith('body.editing'):
        return None
    if sel == ':root[data-theme="dark"]':
        return '.dark ' + S
    if sel in (':root', 'body', 'html'):
        return S
    if sel.startswith((':root', 'body', 'html')):
        raise SystemExit('unhandled selector: ' + sel)
    return S + ' ' + sel


def scope(text):
    out, i = [], 0
    while i < len(text):
        j = text.find('{', i)
        if j < 0:
            break
        prelude = text[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if text[k] == '{':
                depth += 1
            elif text[k] == '}':
                depth -= 1
            k += 1
        inner = text[j + 1:k - 1]
        i = k
        if prelude.startswith('@media'):
            if 'prefers-color-scheme' in prelude:
                continue  # the site's theme toggle decides, not the OS
            out.append(prelude + '{' + scope(inner) + '}')
        elif prelude.startswith('@'):
            out.append(prelude + '{' + inner + '}')
        else:
            sels = [x for x in map(scope_sel, split_top(prelude)) if x]
            if sels:
                out.append(','.join(sels) + '{' + inner.strip() + '}')
    return '\n'.join(out)


scoped = scope(re.sub(r'/\*.*?\*/', '', css, flags=re.S))
for k, v in (
    ('"Bricolage Grotesque"', 'var(--font-ycjdt-display)'),
    ('"Instrument Sans"', 'var(--font-ycjdt-body)'),
    ('"IBM Plex Mono"', 'var(--font-ycjdt-mono)'),
):
    assert k in scoped, k
    scoped = scoped.replace(k, v)

# The site's global reset (Tailwind preflight) would otherwise restyle the
# article. Roll HTML elements back to browser defaults first; SVG is left out
# because `revert` would also discard its presentation attributes. `:where`
# keeps the rule weaker than every scoped rule that follows it.
head = f"""/* Generated by scripts/research/build_ycjdt_site.py. Do not edit by hand. */
{S} :where(:not(svg, svg *, img)) {{
  all: revert;
}}
{S} svg,
{S} img {{
  display: inline;
  vertical-align: baseline;
  max-width: none;
}}
"""
d = site / 'src/app/research/you-can-just-do-things'
d.mkdir(parents=True, exist_ok=True)
(d / 'article.css').write_text(head + scoped + '\n')
(d / 'content.ts').write_text(
    '// Generated by scripts/research/build_ycjdt_site.py. Do not edit by hand.\n'
    'export const ARTICLE_HTML = ' + json.dumps(body, ensure_ascii=False) + '\n'
)


def sub(old, new):
    global js
    assert js.count(old) == 1, (old, js.count(old))
    js = js.replace(old, new)


# Theme tokens now live on the article element, and the site toggles a class.
sub('getComputedStyle(document.documentElement)', 'getComputedStyle(ROOT)')
sub(
    'new MutationObserver(redrawAll).observe(document.documentElement,{attributes:true,attributeFilter:["data-theme"]});',
    'const themeObs=new MutationObserver(redrawAll); themeObs.observe(document.documentElement,{attributes:true,attributeFilter:["class"]}); SIG.addEventListener("abort",()=>{themeObs.disconnect(); clearInterval(atimer)});',
)
sub('matchMedia("(prefers-color-scheme: dark)").addEventListener("change",redrawAll);', '')
# Page-level listeners must go when the reader navigates away inside the site.
sub('document.addEventListener("click",e=>{', 'ROOT.addEventListener("click",e=>{')
sub('wideMq.addEventListener("change",syncTerms);', 'wideMq.addEventListener("change",syncTerms,{signal:SIG});')
m = re.search(r'addEventListener\("resize",\(\)=>\{clearTimeout\(rt\);rt=setTimeout\(\(\)=>\{[^}]*\},\d+\)\}\)', js)
assert m
js = js[:m.start()] + m.group(0)[:-1] + ',{signal:SIG})' + js[m.end():]

js = (
    '/* eslint-disable */\n'
    '// Generated by scripts/research/build_ycjdt_site.py. Do not edit by hand.\n'
    '// Draws the charts, maps and tweet cards into the article element and\n'
    '// returns a function that removes its page-level listeners.\n'
    'export default function mount(ROOT){\n'
    'const AC=new AbortController(), SIG=AC.signal;\n' + js + '\nreturn ()=>AC.abort();\n}\n'
)
(d / 'drawArticle.js').write_text(js)
print('css', len(head + scoped), 'html', len(body), 'js', len(js))
