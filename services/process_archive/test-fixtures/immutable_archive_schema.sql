CREATE ROLE authenticated;
CREATE SCHEMA private;
CREATE SCHEMA auth;
CREATE SCHEMA storage;
CREATE TABLE public.archive_upload(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id text NOT NULL, username text, upload_phase text);
CREATE TABLE storage.objects(name text PRIMARY KEY, bucket_id text NOT NULL);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql AS $$SELECT '{"app_metadata":{"user_name":"fixture_owner","provider_id":"123"}}'::jsonb$$;
CREATE FUNCTION storage.foldername(text) RETURNS text[] LANGUAGE sql AS $$SELECT (string_to_array($1,'/'))[1:array_length(string_to_array($1,'/'),1)-1]$$;
CREATE FUNCTION storage.filename(text) RETURNS text LANGUAGE sql AS $$SELECT (string_to_array($1,'/'))[array_length(string_to_array($1,'/'),1)]$$;
CREATE FUNCTION public.assert_archive_upload_allowed(text,text) RETURNS boolean LANGUAGE sql AS $$SELECT true$$;
CREATE POLICY "Users can update their own archive" ON storage.objects FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY test_read ON storage.objects FOR SELECT TO authenticated USING (true);
GRANT USAGE ON SCHEMA storage,auth TO authenticated;
GRANT SELECT,UPDATE ON storage.objects TO authenticated;
